import { Router } from 'express';
import { requireAuth, allow } from '../auth.js';
import * as operations from '../operations.js';
import { operationsWorkspace } from '../operations-workspace.js';

export const operationsRouter = Router();
operationsRouter.use('/operations', requireAuth, allow(...operations.OPERATION_SECTIONS));
const get = (path, handler) => operationsRouter.get(`/operations${path}`, (req, res) => res.json(handler(req)));
const post = (path, handler) => operationsRouter.post(`/operations${path}`, (req, res) => res.json(handler(req)));
const patch = (path, handler) => operationsRouter.patch(`/operations${path}`, (req, res) => res.json(handler(req)));
get('/bootstrap', (req) => operationsWorkspace(req.user,req.query));
get('/matches/:id', (req) => operations.matchDossier(req.user, req.params.id));
get('/incidents/:id', (req) => operations.incidentDetail(req.user, req.params.id));
post('/incidents', (req) => operations.createIncident(req.user, req.body || {}));
patch('/incidents/:id', (req) => operations.updateIncident(req.user, req.params.id, req.body || {}));
post('/incidents/:id/notes', (req) => operations.addIncidentNote(req.user, req.params.id, req.body || {}));
post('/incidents/:id/resolve', (req) => operations.resolveIncident(req.user, req.params.id, req.body || {}));
post('/assignments', (req) => operations.createAssignment(req.user, req.body || {}));
patch('/assignments/:id', (req) => operations.updateAssignment(req.user, req.params.id, req.body || {}));
post('/matches/:id/notes', (req) => operations.addCasterNote(req.user, req.params.id, req.body || {}));
operationsRouter.put('/operations/matches/:id/production', (req, res) => res.json(operations.updateProduction(req.user, req.params.id, req.body || {})));
post('/matches/:id/content', (req) => operations.createMatchContent(req.user, req.params.id));
post('/stats/:id/review', (req) => operations.reviewStatistics(req.user, req.params.id, req.body || {}));
get('/stats/:id', (req) => operations.statisticsDetail(req.user, req.params.id));
post('/stats/:id/correct', (req) => operations.correctStatistics(req.user, req.params.id, req.body || {}));
post('/competition/commands', (req) => operations.prepareCompetitionCommand(req.user, req.body || {}));
post('/clubs/:id/review', (req) => operations.reviewClub(req.user, req.params.id, req.body || {}));
post('/deliveries/:id/retry', (req) => operations.retryDelivery(req.user, req.params.id, req.body || {}));
post('/sanctions', (req) => operations.createSanction(req.user, req.body || {}));
post('/sanctions/:id/submit', (req) => operations.submitSanction(req.user, req.params.id, req.body || {}));
post('/sanctions/:id/appeal', (req) => operations.appealSanction(req.user, req.params.id, req.body || {}));
post('/sanctions/:id/review', (req) => operations.reviewSanction(req.user, req.params.id, req.body || {}));
post('/sanctions/:id/revoke', (req) => operations.revokeSanction(req.user, req.params.id, req.body || {}));
post('/commands/:id/cancel', (req) => operations.cancelCommand(req.user, req.params.id, req.body || {}));

import test,{after} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {randomUUID} from 'node:crypto';
const temporary=fs.mkdtempSync(path.join(os.tmpdir(),'ctp-ranked-club-qa-'));
process.env.DATA_DIR=temporary;process.env.DB_PATH=path.join(temporary,'qa.db');
const operations=await import('../server/operations.js');
const {db}=await import('../server/db.js');
const {describeUser}=await import('../server/auth.js');
const userId=Number(db.prepare('INSERT INTO users(username,name,password_hash,is_admin,created_at) VALUES(?,?,?,?,?)').run('admin-ranked-qa','QA administrator','unused',1,Date.now()).lastInsertRowid);
const admin=describeUser(db.prepare('SELECT * FROM users WHERE id=?').get(userId));
const noAdmin={...admin,is_admin:false,sections:['operaciones','clubes']};
after(()=>{db.close();assert.ok(path.resolve(temporary).startsWith(path.resolve(os.tmpdir())+path.sep));fs.rmSync(temporary,{recursive:true,force:true,maxRetries:5});});
const future=offset=>new Date(Date.now()+offset*86400000).toISOString();
const initial={current:{id:randomUUID(),name:'SEASON 1',sequence:1,manager_version:3,starts_at:'2026-01-01T00:00:00Z',ends_at:null},scheduled:null,active_matches:1,waiting_players:4,reset_divisions:2,observed_at:new Date().toISOString()};
const payload={name:'SEASON 2',starts_at:future(2),ends_at:future(30),reason:'Programación oficial revisada por coordinación'};
test('season preparation uses explicit capabilities, admin permissions and source revisions',()=>{
 operations.rememberRankedState(initial);
 const input={type:'ranked.season.schedule',target_id:initial.current.id,expected_version:3,payload};
 assert.throws(()=>operations.prepareRankedCommand(admin,input,initial),{status:422});
 operations.setIntegrationStatus({supported_actions:['ranked.season.schedule','ranked.season.update','ranked.season.cancel','club.create']});
 assert.throws(()=>operations.prepareRankedCommand(noAdmin,input,initial),{status:403});
 assert.throws(()=>operations.prepareRankedCommand(admin,{...input,expected_version:2},initial),{status:409});
 const first=operations.prepareRankedCommand(admin,input,initial).command;
 assert.equal(first.expected_version,3);assert.equal(first.status,'pending');
 assert.equal(operations.prepareRankedCommand(admin,input,initial).command.id,first.id);
 assert.equal(operations.bootstrap(admin).commands.some(row=>row.id===first.id),true);
 assert.equal(operations.bootstrap(noAdmin).commands.some(row=>row.id===first.id),false);
 operations.cancelCommand(admin,first.id,{expected_updated_at:first.updated_at});
});
test('future update/cancel targets the scheduled version and blocks after boundary',()=>{
 const scheduled={...initial,current:{...initial.current,ends_at:payload.starts_at},scheduled:{id:randomUUID(),name:payload.name,manager_version:2,starts_at:payload.starts_at,ends_at:payload.ends_at}};
 operations.rememberRankedState(scheduled);
 const input={type:'ranked.season.cancel',target_id:scheduled.scheduled.id,expected_version:2,payload:{reason:'Calendario futuro retirado por coordinación'}};
 assert.throws(()=>operations.prepareRankedCommand(admin,{...input,target_id:initial.current.id},scheduled),{status:400});
 assert.throws(()=>operations.prepareRankedCommand(admin,input,{...scheduled,current:{...scheduled.current,ends_at:'2020-01-01T00:00:00Z'}}),{status:409});
 const prepared=operations.prepareRankedCommand(admin,input,scheduled).command;
 assert.equal(prepared.resource_id,scheduled.scheduled.id);assert.equal(prepared.expected_version,2);
 operations.cancelCommand(admin,prepared.id,{expected_updated_at:prepared.updated_at});
});
test('manual club proposals are private, deduplicate retries and never fabricate official clubs',()=>{
 const club={type:'club.create',payload:{name:'QA Manual Club',tag:'QAMC',leader_id:randomUUID(),reason:'Alta del club con líder registrado y pago externo'}};
 assert.throws(()=>operations.prepareManualClubCommand(noAdmin,club),{status:403});
 const prepared=operations.prepareManualClubCommand(admin,club).command;
 assert.equal(operations.prepareManualClubCommand(admin,club).command.id,prepared.id);
 assert.throws(()=>operations.prepareManualClubCommand(admin,{...club,payload:{...club.payload,name:'Otra propuesta'}}),{status:409});
 assert.equal(operations.bootstrap(admin).clubs.some(row=>row.id===prepared.target_id),false);
 assert.equal(operations.bootstrap(admin).commands.some(row=>row.id===prepared.id),true);
 assert.equal(operations.bootstrap(noAdmin).commands.some(row=>row.id===prepared.id),false);
 assert.equal(prepared.expected_version,0);assert.equal(prepared.payload.pass_active,undefined);assert.equal(prepared.payload.verified,undefined);
});
